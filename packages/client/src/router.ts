export const DOTREACT_NAVIGATION_MEDIA_TYPE = "application/vnd.dotreact.navigation+json";

export interface DotReactMetadata {
  readonly title?: string;
  readonly description?: string;
  readonly noIndex?: boolean;
  readonly links?: readonly Readonly<Record<string, string>>[];
  readonly scripts?: readonly DotReactScriptDescriptor[];
}

export type DotReactScriptStrategy = "beforeInteractive" | "afterInteractive" | "lazyOnload";

export interface DotReactScriptDescriptor {
  readonly src: string;
  readonly strategy?: DotReactScriptStrategy;
  readonly id?: string;
  readonly type?: string;
  readonly integrity?: string;
  readonly crossOrigin?: "anonymous" | "use-credentials";
  readonly referrerPolicy?: string;
}

export interface DotReactPageModule {
  readonly default: ComponentType<Record<string, unknown>>;
  readonly metadata?: DotReactMetadata | ((props: Record<string, unknown>) => DotReactMetadata);
}

/** Data supplied to every layout around the current page. */
export interface DotReactLayoutProps<PageProps = unknown> extends PropsWithChildren {
  /** The same C#-loaded props object received by the leaf page. */
  readonly pageProps: PageProps;
  /** Canonical path and query for the current render/navigation when available. */
  readonly url?: string;
}

/** Declares a typed DRX layout while preserving an ordinary React component. */
export function defineLayout<PageProps>(
  component: FunctionComponent<DotReactLayoutProps<PageProps>>
): FunctionComponent<DotReactLayoutProps<PageProps>> {
  return component;
}

export interface DotReactBoundaryModules {
  readonly notFound?: DotReactPageModule;
  readonly error?: DotReactPageModule;
  readonly loading?: DotReactPageModule;
}

export interface DotReactLoadedRoute {
  readonly page: DotReactPageModule;
  readonly layouts: readonly ComponentType<DotReactLayoutProps<any>>[];
  readonly boundaries: DotReactBoundaryModules;
}

export type DotReactRouteLoader = () => Promise<DotReactLoadedRoute>;

export interface DotReactNavigationPayload {
  readonly protocolVersion: 1;
  readonly requestId: string;
  readonly moduleId: string;
  readonly url: string;
  readonly props: Record<string, unknown>;
  readonly csrfToken?: string | null;
  readonly boundaryKind?: "not-found" | "error" | null;
  readonly statusCode?: number;
}

export interface DotReactNavigateOptions {
  readonly replace?: boolean;
  readonly scroll?: boolean;
}

export interface DotReactRouterValue {
  readonly pending: boolean;
  readonly url: string;
  navigate(href: string, options?: DotReactNavigateOptions): Promise<void>;
  prefetch(href: string): Promise<void>;
  refresh(): Promise<void>;
  invalidate(paths: readonly string[]): void;
}

export interface DotReactAppProps {
  readonly initial: DotReactNavigationPayload;
  readonly pages: Readonly<Record<string, DotReactPageModule>>;
  /** Raw route modules let the router preserve shared layout component identities. */
  readonly routeModules?: Readonly<Record<string, DotReactPageModule>>;
  readonly routeLayouts?: Readonly<Record<string, readonly ComponentType<DotReactLayoutProps<any>>[]>>;
  readonly boundaries?: Readonly<Record<string, DotReactBoundaryModules>>;
  /** Browser-only lazy route modules generated by the DotReact Vite plugin. */
  readonly routeLoaders?: Readonly<Record<string, DotReactRouteLoader>>;
  readonly fetch?: typeof globalThis.fetch;
  readonly window?: Window;
  readonly document?: Document;
}

const RouterContext = createContext<DotReactRouterValue | undefined>(undefined);

const navigationHeadAttributes: Readonly<Record<"meta" | "link", ReadonlySet<string>>> = {
  meta: new Set(["charset", "content", "http-equiv", "name", "property"]),
  link: new Set([
    "as", "crossorigin", "fetchpriority", "href", "hreflang", "imagesizes", "imagesrcset",
    "integrity", "media", "referrerpolicy", "rel", "sizes", "type"
  ])
};

/**
 * Declares the generated C# props model of a DRX page without adding runtime
 * behavior. Keeping this as ordinary TypeScript preserves editor and refactor support.
 */
export function definePage<Props>(component: ComponentType<Props>): ComponentType<Props> {
  return component;
}

/** True only after React has hydrated the browser tree. */
export function useDotReactHydrated(): boolean {
  const [hydrated, setHydrated] = useState(false);
  useEffect(() => setHydrated(true), []);
  return hydrated;
}

export interface DotReactClientOnlyProps extends PropsWithChildren {
  readonly fallback?: ReactElement | null;
}

/** Renders a deterministic fallback during SSR and reveals browser-only UI after hydration. */
export function DotReactClientOnly({ children, fallback = null }: DotReactClientOnlyProps): ReactElement | null {
  return useDotReactHydrated() ? createElement(Fragment, null, children)
    : fallback;
}

function isPayload(value: unknown): value is DotReactNavigationPayload {
  if (typeof value !== "object" || value === null) return false;
  const item = value as Record<string, unknown>;
  return item.protocolVersion === 1
    && typeof item.requestId === "string"
    && typeof item.moduleId === "string"
    && typeof item.url === "string"
    && typeof item.props === "object"
    && item.props !== null
    && (item.boundaryKind === undefined || item.boundaryKind === null
      || item.boundaryKind === "not-found" || item.boundaryKind === "error");
}

export async function fetchDotReactNavigation(
  href: string,
  fetchImplementation: typeof globalThis.fetch = globalThis.fetch,
  signal?: AbortSignal
): Promise<DotReactNavigationPayload> {
  if (fetchImplementation === undefined) throw new Error("Fetch is not available in this environment.");
  const response = await fetchImplementation(href, {
    method: "GET",
    credentials: "same-origin",
    headers: {
      "Accept": DOTREACT_NAVIGATION_MEDIA_TYPE,
      "X-DotReact-Navigation": "1"
    },
    ...(signal === undefined ? {} : { signal })
  });
  const mediaType = (response.headers.get("content-type") ?? "").split(";", 1)[0]?.trim().toLowerCase();
  if (mediaType !== DOTREACT_NAVIGATION_MEDIA_TYPE) {
    throw new DotReactDocumentNavigation(response.url || href, response.status);
  }
  let body: unknown;
  try { body = await response.json(); }
  catch { throw new Error("DotReact navigation returned invalid JSON."); }
  if (!isPayload(body)) throw new Error("DotReact navigation returned an invalid payload.");
  if (!response.ok && body.boundaryKind === undefined)
    throw new Error(`DotReact navigation failed with HTTP ${response.status}.`);
  return body;
}

export class DotReactDocumentNavigation extends Error {
  readonly url: string;
  readonly status: number;

  constructor(url: string, status: number) {
    super(`A full document navigation is required for ${url}.`);
    this.name = "DotReactDocumentNavigation";
    this.url = url;
    this.status = status;
  }
}

function waitForNavigation<T>(promise: Promise<T>, signal?: AbortSignal): Promise<T> {
  if (signal === undefined) return promise;
  if (signal.aborted) return Promise.reject(new DOMException("Navigation aborted.", "AbortError"));
  return new Promise<T>((resolve, reject) => {
    const abort = (): void => reject(new DOMException("Navigation aborted.", "AbortError"));
    signal.addEventListener("abort", abort, { once: true });
    promise.then(resolve, reject).finally(() => signal.removeEventListener("abort", abort));
  });
}

function resolvePage(
  state: DotReactNavigationPayload,
  pages: Readonly<Record<string, DotReactPageModule>>,
  boundaries: Readonly<Record<string, DotReactBoundaryModules>>
): DotReactPageModule | undefined {
  if (state.boundaryKind === "not-found") return boundaries[state.moduleId]?.notFound;
  if (state.boundaryKind === "error") return boundaries[state.moduleId]?.error;
  return pages[state.moduleId];
}

function updateMetadata(document: Document, module: DotReactPageModule, props: Record<string, unknown>): void {
  const configured = module.metadata;
  const metadata = typeof configured === "function" ? configured(props) : configured ?? {};
  if (metadata.title !== undefined) document.title = metadata.title;
  document.head.querySelectorAll("[data-dotreact-navigation-head]").forEach(element => element.remove());
  const append = (tag: "meta" | "link", attributes: Readonly<Record<string, string>>): void => {
    const element = document.createElement(tag);
    element.setAttribute("data-dotreact-navigation-head", "");
    for (const [name, value] of Object.entries(attributes)) {
      const normalizedName = name.toLowerCase();
      if (navigationHeadAttributes[tag].has(normalizedName)) element.setAttribute(normalizedName, value);
    }
    document.head.append(element);
  };
  if (metadata.description !== undefined) append("meta", { name: "description", content: metadata.description });
  if (metadata.noIndex === true) append("meta", { name: "robots", content: "noindex,nofollow" });
  for (const link of metadata.links ?? []) append("link", link);
  for (const script of metadata.scripts ?? []) installMetadataScript(document, script);
}

function installMetadataScript(document: Document, descriptor: DotReactScriptDescriptor): void {
  if (!isSafeScriptSource(descriptor.src)) return;
  const key = descriptor.id ?? descriptor.src;
  if ([...document.scripts].some(script => script.dataset.dotreactScript === key)) return;
  const install = (): void => {
    if ([...document.scripts].some(script => script.dataset.dotreactScript === key)) return;
    const script = document.createElement("script");
    script.src = descriptor.src;
    script.dataset.dotreactScript = key;
    if (descriptor.type !== undefined) script.type = descriptor.type;
    if (descriptor.integrity !== undefined) script.integrity = descriptor.integrity;
    if (descriptor.crossOrigin !== undefined) script.crossOrigin = descriptor.crossOrigin;
    if (descriptor.referrerPolicy !== undefined) script.referrerPolicy = descriptor.referrerPolicy;
    document.head.append(script);
  };
  if (descriptor.strategy !== "lazyOnload") {
    install();
    return;
  }
  const window = document.defaultView;
  if (document.readyState === "complete" || window === null) window?.setTimeout(install, 0) ?? install();
  else window.addEventListener("load", () => window.setTimeout(install, 0), { once: true });
}

function isSafeScriptSource(src: string): boolean {
  if (src.startsWith("/") && !src.startsWith("//") && !src.includes("\\") && !src.includes("\0"))
    return !src.split(/[?#]/, 1)[0]!.split("/").some(segment => segment === "." || segment === "..");
  try {
    const parsed = new URL(src);
    return parsed.protocol === "https:" && parsed.username === "" && parsed.password === "";
  } catch { return false; }
}

export function DotReactApp({ initial, pages, routeModules = pages, routeLayouts = {}, boundaries = {}, routeLoaders = {}, fetch: fetchOption, window: windowOption,
  document: documentOption }: DotReactAppProps): ReactElement {
  const browserWindow = windowOption ?? (typeof window === "undefined" ? undefined : window);
  const browserDocument = documentOption ?? browserWindow?.document;
  const fetchImplementation = fetchOption ?? globalThis.fetch;
  const [state, setState] = useState(initial);
  const [pending, setPending] = useState(false);
  const stateRef = useRef(state);
  const navigationRef = useRef<AbortController | undefined>(undefined);
  const cacheRef = useRef(new Map<string, DotReactNavigationPayload>());
  const inFlightRef = useRef(new Map<string, Promise<DotReactNavigationPayload>>());
  const routeInFlightRef = useRef(new Map<string, Promise<void>>());
  stateRef.current = state;

  const ensureRoute = useCallback(async (moduleId: string): Promise<void> => {
    if (routeModules[moduleId] !== undefined) return;
    const existing = routeInFlightRef.current.get(moduleId);
    if (existing !== undefined) return await existing;
    const loader = routeLoaders[moduleId];
    if (loader === undefined) throw new Error(`Unknown DotReact route chunk: ${moduleId}`);
    const pendingRoute = loader().then(loaded => {
      (pages as Record<string, DotReactPageModule>)[moduleId] = loaded.page;
      (routeModules as Record<string, DotReactPageModule>)[moduleId] = loaded.page;
      (routeLayouts as Record<string, readonly ComponentType<DotReactLayoutProps<any>>[]>)[moduleId] = loaded.layouts;
      (boundaries as Record<string, DotReactBoundaryModules>)[moduleId] = loaded.boundaries;
    }).finally(() => routeInFlightRef.current.delete(moduleId));
    routeInFlightRef.current.set(moduleId, pendingRoute);
    await pendingRoute;
  }, [boundaries, pages, routeLayouts, routeLoaders, routeModules]);

  const load = useCallback(async (href: string, signal?: AbortSignal): Promise<DotReactNavigationPayload> => {
    if (browserWindow === undefined) throw new Error("DotReact navigation requires a browser window.");
    const target = new URL(href, browserWindow.location.href);
    if (target.origin !== browserWindow.location.origin)
      throw new DotReactDocumentNavigation(target.href, 0);
    const key = `${target.pathname}${target.search}`;
    const cached = cacheRef.current.get(key);
    if (cached !== undefined) return cached;
    const existing = inFlightRef.current.get(key);
    if (existing !== undefined) return waitForNavigation(existing, signal);
    const pendingRequest = fetchDotReactNavigation(key, fetchImplementation).then(async payload => {
      await ensureRoute(payload.moduleId);
      if (cacheRef.current.size >= 32) cacheRef.current.delete(cacheRef.current.keys().next().value as string);
      cacheRef.current.set(key, payload);
      return payload;
    }).finally(() => inFlightRef.current.delete(key));
    inFlightRef.current.set(key, pendingRequest);
    return waitForNavigation(pendingRequest, signal);
  }, [browserWindow, ensureRoute, fetchImplementation]);

  const navigate = useCallback(async (href: string, options: DotReactNavigateOptions = {}): Promise<void> => {
    if (browserWindow === undefined) return;
    navigationRef.current?.abort();
    const controller = new AbortController();
    navigationRef.current = controller;
    setPending(true);
    try {
      const payload = await load(href, controller.signal);
      const resolved = new URL(payload.url, browserWindow.location.href);
      startTransition(() => setState(payload));
      if (options.replace === true) browserWindow.history.replaceState({ dotreact: true }, "", resolved);
      else browserWindow.history.pushState({ dotreact: true }, "", resolved);
      if (options.scroll !== false) browserWindow.scrollTo({ top: 0, left: 0, behavior: "instant" });
    } catch (error) {
      if (error instanceof DOMException && error.name === "AbortError") return;
      if (error instanceof DotReactDocumentNavigation) browserWindow.location.assign(error.url);
      else throw error;
    } finally {
      if (navigationRef.current === controller) {
        navigationRef.current = undefined;
        setPending(false);
      }
    }
  }, [browserWindow, load]);

  const prefetch = useCallback(async (href: string): Promise<void> => {
    try { await load(href); }
    catch (error) {
      if (!(error instanceof DotReactDocumentNavigation)
        && !(error instanceof DOMException && error.name === "AbortError")) throw error;
    }
  }, [load]);

  const invalidate = useCallback((paths: readonly string[]): void => {
    for (const path of paths) {
      if (!path.startsWith("/") || path.startsWith("//")) continue;
      const invalidated = new URL(path, browserWindow?.location.href ?? "http://dotreact.invalid");
      const key = `${invalidated.pathname}${invalidated.search}`;
      cacheRef.current.delete(key);
    }
  }, [browserWindow]);

  const refresh = useCallback(async (): Promise<void> => {
    if (browserWindow === undefined) return;
    const current = `${browserWindow.location.pathname}${browserWindow.location.search}`;
    invalidate([current]);
    await navigate(current, { replace: true, scroll: false });
  }, [browserWindow, invalidate, navigate]);

  useEffect(() => {
    if (browserWindow === undefined) return;
    const popstate = (): void => { void navigate(browserWindow.location.href, { replace: true, scroll: false }); };
    const revalidate = (event: Event): void => {
      const paths = (event as CustomEvent<unknown>).detail;
      if (!Array.isArray(paths) || !paths.every(path => typeof path === "string")) return;
      invalidate(paths);
      const current = `${browserWindow.location.pathname}${browserWindow.location.search}`;
      if (paths.includes(current) || paths.includes(browserWindow.location.pathname)) void refresh();
    };
    browserWindow.addEventListener("popstate", popstate);
    browserWindow.addEventListener("dotreact:revalidate", revalidate);
    return () => {
      browserWindow.removeEventListener("popstate", popstate);
      browserWindow.removeEventListener("dotreact:revalidate", revalidate);
      navigationRef.current?.abort();
    };
  }, [browserWindow, invalidate, navigate, refresh]);

  const pageModule = resolvePage(state, routeModules, boundaries);
  if (pageModule === undefined) throw new Error(`Unknown DotReact page module: ${state.moduleId}`);
  useEffect(() => {
    if (browserDocument !== undefined) updateMetadata(browserDocument, pageModule, state.props);
  }, [browserDocument, pageModule, state.props]);
  const router = useMemo<DotReactRouterValue>(() => ({ pending, url: state.url, navigate, prefetch, refresh, invalidate }),
    [invalidate, navigate, pending, prefetch, refresh, state.url]);
  const displayModule = pending ? boundaries[state.moduleId]?.loading ?? pageModule : pageModule;
  let content: ReactElement = createElement(displayModule.default, pending ? {} : state.props);
  for (const Layout of [...(routeLayouts[state.moduleId] ?? [])].reverse())
    content = createElement(Layout, { pageProps: state.props, url: state.url }, content);
  return createElement(RouterContext.Provider, { value: router }, content);
}

export function useDotReactRouter(): DotReactRouterValue {
  const value = useContext(RouterContext);
  if (value === undefined) throw new Error("useDotReactRouter must be used inside DotReactApp.");
  return value;
}

export interface DotReactLinkProps extends AnchorHTMLAttributes<HTMLAnchorElement> {
  readonly href: string;
  readonly prefetch?: boolean;
  readonly replace?: boolean;
  readonly scroll?: boolean;
}

function shouldNavigate(
  event: ReactMouseEvent<HTMLAnchorElement>,
  target: string | undefined,
  download: AnchorHTMLAttributes<HTMLAnchorElement>["download"]
): boolean {
  return !event.defaultPrevented && event.button === 0 && !event.metaKey && !event.ctrlKey && !event.shiftKey
    && !event.altKey && target !== "_blank" && download === undefined;
}

export const DotReactLink = forwardRef(function DotReactLink(
  { href, prefetch = true, replace, scroll, onClick, onPointerEnter, onFocus, ...anchor }: DotReactLinkProps,
  ref: Ref<HTMLAnchorElement>
): ReactElement {
  const router = useDotReactRouter();
  const warm = (): void => { if (prefetch) void router.prefetch(href); };
  return createElement("a", {
    ...anchor,
    ref,
    href,
    onPointerEnter(event: ReactPointerEvent<HTMLAnchorElement>) { onPointerEnter?.(event); warm(); },
    onFocus(event: ReactFocusEvent<HTMLAnchorElement>) { onFocus?.(event); warm(); },
    onClick(event: ReactMouseEvent<HTMLAnchorElement>) {
      onClick?.(event);
      if (!shouldNavigate(event, anchor.target, anchor.download)) return;
      event.preventDefault();
      void router.navigate(href, {
        ...(replace === undefined ? {} : { replace }),
        ...(scroll === undefined ? {} : { scroll })
      });
    }
  });
});
