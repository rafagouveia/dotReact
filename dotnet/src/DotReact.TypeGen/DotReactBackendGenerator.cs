using System.Reflection;
using System.Text;
using System.Text.Json;
using DotReact.AspNetCore;

namespace DotReact.TypeGen;

public sealed record DotReactPageContract(string ModuleId, string Pattern, Type PropsType, string Routing = "explicit");

public sealed record DotReactActionContract(string Id, string ExportName, Type RequestType, Type ResponseType);

public sealed record DotReactBackendContract(
    IReadOnlyList<DotReactPageContract> Pages,
    IReadOnlyList<DotReactActionContract> Actions)
{
    public IReadOnlyList<Type> ContractTypes => Pages.Select(page => page.PropsType)
        .Concat(Actions.SelectMany(action => new[] { action.RequestType, action.ResponseType }))
        .Distinct()
        .ToArray();
}

public sealed class DotReactBackendGenerator
{
    private const string PageAttributeName = "DotReact.AspNetCore.DotReactPageAttribute";
    private const string PageInterfaceName = "DotReact.AspNetCore.IDotReactPage`1";
    private const string ResultPageInterfaceName = "DotReact.AspNetCore.IDotReactResultPage`1";
    private const string ActionAttributeName = "DotReact.AspNetCore.DotReactActionAttribute";
    private const string ActionInterfaceName = "DotReact.AspNetCore.IDotReactAction`2";

    public DotReactBackendContract Discover(Assembly assembly)
    {
        ArgumentNullException.ThrowIfNull(assembly);
        return Discover([assembly]);
    }

    public DotReactBackendContract Discover(IEnumerable<Assembly> assemblies)
    {
        ArgumentNullException.ThrowIfNull(assemblies);
        var candidates = assemblies.Distinct().ToArray();
        if (candidates.Length == 0)
            throw new ArgumentException("At least one assembly is required.", nameof(assemblies));

        var pages = new List<DotReactPageContract>();
        var actions = new List<DotReactActionContract>();
        foreach (var assembly in candidates)
        foreach (var type in assembly.GetTypes().Where(type => type is { IsClass: true, IsAbstract: false }))
        {
            var pageAttribute = FindAttribute(type, PageAttributeName);
            if (pageAttribute is not null)
            {
                var contract = FindPageInterface(type);
                var moduleId = ReadRequiredString(pageAttribute, "ModuleId", type);
                var convention = UsesRouteConvention(pageAttribute);
                pages.Add(new DotReactPageContract(
                    moduleId,
                    convention ? DotReactRouteConvention.InferPattern(moduleId) : ReadRequiredString(pageAttribute, "Pattern", type),
                    contract.GenericTypeArguments[0],
                    convention ? "convention" : "explicit"));
            }

            var actionAttribute = FindAttribute(type, ActionAttributeName);
            if (actionAttribute is not null)
            {
                var contract = FindInterface(type, ActionInterfaceName, 2, "action");
                var id = ReadRequiredString(actionAttribute, "Id", type);
                actions.Add(new DotReactActionContract(
                    id,
                    ToExportName(id),
                    contract.GenericTypeArguments[0],
                    contract.GenericTypeArguments[1]));
            }
        }

        EnsureUnique(pages, page => page.ModuleId, "page module id");
        EnsureUnique(pages, page => page.Pattern, "page route pattern");
        EnsureUnique(actions, action => action.Id, "action id");
        EnsureUnique(actions, action => action.ExportName, "action TypeScript export");

        return new DotReactBackendContract(
            pages.OrderBy(page => page.ModuleId, StringComparer.Ordinal).ToArray(),
            actions.OrderBy(action => action.Id, StringComparer.Ordinal).ToArray());
    }

    public string GenerateManifest(DotReactBackendContract contract)
    {
        var model = new
        {
            schemaVersion = 2,
            pages = contract.Pages.Select(page => new
            {
                page.ModuleId,
                page.Pattern,
                page.Routing,
                propsType = StableTypeName(page.PropsType)
            }),
            actions = contract.Actions.Select(action => new
            {
                action.Id,
                action.ExportName,
                requestType = StableTypeName(action.RequestType),
                responseType = StableTypeName(action.ResponseType)
            })
        };
        return JsonSerializer.Serialize(model, new JsonSerializerOptions
        {
            WriteIndented = true,
            PropertyNamingPolicy = JsonNamingPolicy.CamelCase
        }) + "\n";
    }

    public string GenerateActionClient(DotReactBackendContract contract, string contractsImport)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(contractsImport);
        var output = new StringBuilder("// <auto-generated by DotReact.TypeGen />\n\n");
        output.AppendLine("import { createServerAction } from \"@dotreact/client\";");

        var typeNames = contract.Actions
            .SelectMany(action => new[] { DeclarationName(action.RequestType), DeclarationName(action.ResponseType) })
            .Distinct(StringComparer.Ordinal)
            .Order(StringComparer.Ordinal)
            .ToArray();
        if (typeNames.Length > 0)
        {
            output.Append("import type { ").Append(string.Join(", ", typeNames)).Append(" } from ")
                .Append(JsonSerializer.Serialize(contractsImport)).AppendLine(";");
        }

        foreach (var action in contract.Actions)
        {
            output.Append("\nexport const ").Append(action.ExportName)
                .Append(" = createServerAction<").Append(DeclarationName(action.RequestType)).Append(", ")
                .Append(DeclarationName(action.ResponseType)).Append(">(")
                .Append(JsonSerializer.Serialize(action.Id)).AppendLine(");");
        }

        return output.ToString().ReplaceLineEndings("\n");
    }

    private static CustomAttributeData? FindAttribute(MemberInfo type, string fullName) =>
        type.CustomAttributes.SingleOrDefault(attribute => attribute.AttributeType.FullName == fullName);

    private static Type FindInterface(Type type, string definitionName, int arity, string kind)
    {
        var matches = type.GetInterfaces().Where(candidate => candidate.IsGenericType
            && candidate.GetGenericTypeDefinition().FullName == definitionName
            && candidate.GenericTypeArguments.Length == arity).ToArray();
        return matches.Length == 1
            ? matches[0]
            : throw new TypeScriptGenerationException(
                $"DotReact {kind} '{StableTypeName(type)}' must implement exactly one supported contract interface.");
    }

    private static Type FindPageInterface(Type type)
    {
        var matches = type.GetInterfaces().Where(candidate => candidate.IsGenericType
            && candidate.GenericTypeArguments.Length == 1
            && candidate.GetGenericTypeDefinition().FullName is PageInterfaceName or ResultPageInterfaceName).ToArray();
        return matches.Length == 1
            ? matches[0]
            : throw new TypeScriptGenerationException(
                $"DotReact page '{StableTypeName(type)}' must implement exactly one supported page contract interface.");
    }

    private static string ReadRequiredString(CustomAttributeData attribute, string propertyName, Type owner)
    {
        var property = attribute.AttributeType.GetProperty(propertyName);
        var constructorParameter = attribute.Constructor.GetParameters()
            .Select((parameter, index) => (parameter, index))
            .FirstOrDefault(value => string.Equals(value.parameter.Name, propertyName, StringComparison.OrdinalIgnoreCase));
        object? value = constructorParameter.parameter is not null
            ? attribute.ConstructorArguments[constructorParameter.index].Value
            : attribute.NamedArguments.FirstOrDefault(argument => argument.MemberName == property?.Name).TypedValue.Value;
        return value is string text && !string.IsNullOrWhiteSpace(text)
            ? text
            : throw new TypeScriptGenerationException(
                $"DotReact metadata '{propertyName}' is required on '{StableTypeName(owner)}'.");
    }

    private static bool UsesRouteConvention(CustomAttributeData attribute) =>
        !attribute.Constructor.GetParameters().Any(parameter =>
            string.Equals(parameter.Name, "pattern", StringComparison.OrdinalIgnoreCase));

    private static void EnsureUnique<T>(IEnumerable<T> values, Func<T, string> key, string description)
    {
        var duplicate = values.GroupBy(key, StringComparer.Ordinal).FirstOrDefault(group => group.Count() > 1);
        if (duplicate is not null)
            throw new TypeScriptGenerationException($"Duplicate DotReact {description}: '{duplicate.Key}'.");
    }

    private static string ToExportName(string id)
    {
        var pieces = id.Split(['/', '.', '-', '_'], StringSplitOptions.RemoveEmptyEntries);
        if (pieces.Length == 0 || pieces.Any(piece => piece.Any(character =>
                character is not (>= 'A' and <= 'Z')
                and not (>= 'a' and <= 'z')
                and not (>= '0' and <= '9'))))
            throw new TypeScriptGenerationException($"Invalid DotReact action id: '{id}'.");
        var name = char.ToLowerInvariant(pieces[0][0]) + pieces[0][1..];
        return name + string.Concat(pieces.Skip(1).Select(piece => char.ToUpperInvariant(piece[0]) + piece[1..]));
    }

    private static string StableTypeName(Type type) => type.FullName ?? type.Name;

    private static string DeclarationName(Type type) => TypeScriptGenerator.GetTypeScriptDeclarationName(type);
}
