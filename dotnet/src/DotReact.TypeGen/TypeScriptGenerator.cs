using System.Collections;
using System.Globalization;
using System.Reflection;
using System.Text;
using System.Text.Json;
using System.Text.Json.Serialization;

namespace DotReact.TypeGen;

public sealed class TypeScriptGenerator
{
    private static readonly HashSet<Type> NumberTypes =
    [
        typeof(byte), typeof(sbyte), typeof(short), typeof(ushort), typeof(int),
        typeof(uint), typeof(float), typeof(double), typeof(decimal)
    ];

    private static readonly HashSet<Type> StringTypes =
    [
        typeof(Guid), typeof(DateTime), typeof(DateTimeOffset)
    ];

    private readonly NullabilityInfoContext _nullability = new();
    private readonly SortedDictionary<string, Type> _declarations = new(StringComparer.Ordinal);
    private readonly HashSet<Type> _visiting = [];

    public string Generate(IEnumerable<Type> rootTypes)
    {
        ArgumentNullException.ThrowIfNull(rootTypes);

        _declarations.Clear();
        _visiting.Clear();

        var roots = rootTypes.Distinct().OrderBy(GetStableTypeName, StringComparer.Ordinal).ToArray();
        if (roots.Length == 0)
        {
            throw new TypeScriptGenerationException("At least one root type is required.");
        }

        foreach (var root in roots)
        {
            RegisterDeclaration(root, [GetStableTypeName(root)]);
        }

        var output = new StringBuilder("// <auto-generated by DotReact.TypeGen />\n\n");
        var declarations = _declarations.Values.ToArray();
        for (var index = 0; index < declarations.Length; index++)
        {
            WriteDeclaration(output, declarations[index]);
            if (index < declarations.Length - 1)
            {
                output.Append('\n');
            }
        }

        return output.ToString().ReplaceLineEndings("\n");
    }

    private void RegisterDeclaration(Type type, IReadOnlyList<string> path)
    {
        type = Nullable.GetUnderlyingType(type) ?? type;
        if (IsScalar(type) || TryGetDictionaryValue(type, out _) || TryGetEnumerableElement(type, out _))
        {
            _ = MapType(type, null, path);
            return;
        }

        if (!IsDeclaration(type))
        {
            throw Unsupported(type, path);
        }

        var name = GetDeclarationName(type);
        if (_declarations.TryGetValue(name, out var existing))
        {
            if (existing != type)
            {
                throw new TypeScriptGenerationException(
                    $"TypeScript name collision: '{GetStableTypeName(existing)}' and '{GetStableTypeName(type)}' both map to '{name}'.");
            }

            if (_visiting.Contains(type))
            {
                throw new TypeScriptGenerationException($"Cyclic type graph detected at {string.Join(" -> ", path)}.");
            }

            return;
        }

        _declarations.Add(name, type);
        if (type.IsEnum)
        {
            return;
        }

        _visiting.Add(type);
        var polymorphic = GetPolymorphicContract(type);
        if (polymorphic is not null)
        {
            foreach (var derivedType in polymorphic.DerivedTypes)
            {
                RegisterDeclaration(derivedType.Type, path.Append(GetStableTypeName(derivedType.Type)).ToArray());
            }
        }
        else
        {
            foreach (var property in GetProperties(type))
            {
                var propertyPath = path.Append(property.Name).ToArray();
                _ = MapType(property.PropertyType, _nullability.Create(property), propertyPath,
                    IsSerializedAsString(property));
            }
        }

        _visiting.Remove(type);
    }

    private string MapType(
        Type type,
        NullabilityInfo? nullability,
        IReadOnlyList<string> path,
        bool numberAsString = false)
    {
        var nullableValueType = Nullable.GetUnderlyingType(type);
        var isNullable = nullableValueType is not null ||
            (!type.IsValueType && nullability?.ReadState == NullabilityState.Nullable);
        type = nullableValueType ?? type;

        string mapped;
        if (type == typeof(string) || StringTypes.Contains(type))
        {
            mapped = "string";
        }
        else if (type == typeof(bool))
        {
            mapped = "boolean";
        }
        else if (NumberTypes.Contains(type))
        {
            mapped = numberAsString ? "string" : "number";
        }
        else if (type == typeof(long) || type == typeof(ulong) || type == typeof(nint) || type == typeof(nuint))
        {
            if (!numberAsString)
            {
                throw new TypeScriptGenerationException(
                    $"Unsafe numeric type '{GetStableTypeName(type)}' at {string.Join(" -> ", path)}. " +
                    "Annotate the property with [JsonNumberHandling(JsonNumberHandling.WriteAsString)] to preserve precision.");
            }
            mapped = "string";
        }
        else if (TryGetDictionaryValue(type, out var valueType))
        {
            var valueNullability = nullability?.GenericTypeArguments.ElementAtOrDefault(1);
            mapped = $"Record<string, {MapType(valueType, valueNullability, path, numberAsString)}>";
        }
        else if (TryGetEnumerableElement(type, out var elementType))
        {
            var elementNullability = type.IsArray
                ? nullability?.ElementType
                : nullability?.GenericTypeArguments.ElementAtOrDefault(0);
            mapped = $"Array<{MapType(elementType, elementNullability, path, numberAsString)}>";
        }
        else if (IsDeclaration(type))
        {
            RegisterDeclaration(type, path);
            mapped = GetDeclarationName(type);
        }
        else
        {
            throw Unsupported(type, path);
        }

        return isNullable ? $"{mapped} | null" : mapped;
    }

    private void WriteDeclaration(StringBuilder output, Type type)
    {
        var name = GetDeclarationName(type);
        if (type.IsEnum)
        {
            var members = Enum.GetNames(type).OrderBy(value => value, StringComparer.Ordinal);
            output.Append("export type ").Append(name).Append(" = ")
                .Append(string.Join(" | ", members.Select(member => $"\"{member}\"")))
                .AppendLine(";");
            return;
        }

        var polymorphic = GetPolymorphicContract(type);
        if (polymorphic is not null)
        {
            output.Append("export type ").Append(name).AppendLine(" =");
            for (var index = 0; index < polymorphic.DerivedTypes.Count; index++)
            {
                var derivedType = polymorphic.DerivedTypes[index];
                output.Append("  | (").Append(GetDeclarationName(derivedType.Type)).Append(" & { ")
                    .Append(JsonSerializer.Serialize(polymorphic.DiscriminatorPropertyName))
                    .Append(": ").Append(SerializeDiscriminator(derivedType.Discriminator)).Append(" })")
                    .AppendLine(index == polymorphic.DerivedTypes.Count - 1 ? ";" : string.Empty);
            }

            return;
        }

        output.Append("export interface ").Append(name).AppendLine(" {");
        foreach (var property in GetProperties(type))
        {
            var path = new[] { GetStableTypeName(type), property.Name };
            if (IsSerializedAsString(property))
                output.AppendLine("  /** Serialized as a JSON string to preserve numeric precision. */");
            output.Append("  ").Append(ToCamelCase(property.Name)).Append(": ")
                .Append(MapType(property.PropertyType, _nullability.Create(property), path,
                    IsSerializedAsString(property))).AppendLine(";");
        }

        output.AppendLine("}");
    }

    private static PropertyInfo[] GetProperties(Type type) =>
        type.GetProperties(BindingFlags.Instance | BindingFlags.Public)
            .Where(property => property.GetMethod?.IsPublic == true && property.GetIndexParameters().Length == 0)
            .OrderBy(property => property.Name, StringComparer.Ordinal)
            .ToArray();

    private static bool IsScalar(Type type) =>
        type == typeof(string) || type == typeof(bool) || NumberTypes.Contains(type) || StringTypes.Contains(type) ||
        type == typeof(long) || type == typeof(ulong) || type == typeof(nint) || type == typeof(nuint);

    private static bool IsDeclaration(Type type) =>
        type.IsEnum || (type.IsClass && type != typeof(object)) ||
        (type.IsValueType && !type.IsPrimitive && !type.IsGenericType) ||
        (type.IsInterface && HasPolymorphicAttributes(type));

    private static bool TryGetEnumerableElement(Type type, out Type elementType)
    {
        if (type.IsArray)
        {
            elementType = type.GetElementType()!;
            return true;
        }

        var enumerable = type.IsGenericType && type.GetGenericTypeDefinition() == typeof(IEnumerable<>)
            ? type
            : type.GetInterfaces().FirstOrDefault(candidate =>
                candidate.IsGenericType && candidate.GetGenericTypeDefinition() == typeof(IEnumerable<>));
        if (enumerable is not null && type != typeof(string))
        {
            elementType = enumerable.GetGenericArguments()[0];
            return true;
        }

        elementType = null!;
        return false;
    }

    private static bool TryGetDictionaryValue(Type type, out Type valueType)
    {
        var dictionary = type.IsGenericType && type.GetGenericTypeDefinition() == typeof(IDictionary<,>)
            ? type
            : type.GetInterfaces().FirstOrDefault(candidate =>
                candidate.IsGenericType && candidate.GetGenericTypeDefinition() == typeof(IDictionary<,>));

        dictionary ??= type.IsGenericType && type.GetGenericTypeDefinition() == typeof(IReadOnlyDictionary<,>)
            ? type
            : type.GetInterfaces().FirstOrDefault(candidate =>
                candidate.IsGenericType && candidate.GetGenericTypeDefinition() == typeof(IReadOnlyDictionary<,>));

        if (dictionary is not null)
        {
            var arguments = dictionary.GetGenericArguments();
            if (arguments[0] != typeof(string))
            {
                throw new TypeScriptGenerationException(
                    $"Dictionary '{GetStableTypeName(type)}' must use string keys.");
            }

            valueType = arguments[1];
            return true;
        }

        valueType = null!;
        return false;
    }

    public static string GetTypeScriptDeclarationName(Type type)
    {
        ArgumentNullException.ThrowIfNull(type);
        if (type.ContainsGenericParameters)
        {
            throw new TypeScriptGenerationException(
                $"Open generic DTO type '{GetStableTypeName(type)}' is not supported.");
        }
        if (!type.IsGenericType) return type.Name;

        var marker = type.Name.IndexOf('`');
        var baseName = marker < 0 ? type.Name : type.Name[..marker];
        var arguments = type.GetGenericArguments().Select(GetTypeNameToken);
        return baseName + "Of" + string.Join("And", arguments);
    }

    private static string GetDeclarationName(Type type) => GetTypeScriptDeclarationName(type);

    private static string GetTypeNameToken(Type type)
    {
        var nullable = Nullable.GetUnderlyingType(type);
        if (nullable is not null) return "Nullable" + GetTypeNameToken(nullable);
        if (type.IsArray) return "ArrayOf" + GetTypeNameToken(type.GetElementType()!);
        return type.IsGenericType ? GetTypeScriptDeclarationName(type) : type.Name;
    }

    private static bool IsSerializedAsString(PropertyInfo property) =>
        property.GetCustomAttribute<JsonNumberHandlingAttribute>()?.Handling
            .HasFlag(JsonNumberHandling.WriteAsString) == true;

    private static PolymorphicContract? GetPolymorphicContract(Type type)
    {
        var polymorphic = type.GetCustomAttribute<JsonPolymorphicAttribute>(inherit: false);
        var derivedAttributes = type.GetCustomAttributes<JsonDerivedTypeAttribute>(inherit: false).ToArray();
        if (polymorphic is null && derivedAttributes.Length == 0)
        {
            return null;
        }

        var stableName = GetStableTypeName(type);
        if (derivedAttributes.Length == 0)
        {
            throw new TypeScriptGenerationException(
                $"Polymorphic type '{stableName}' must declare at least one [JsonDerivedType].");
        }

        if (polymorphic is not null &&
            polymorphic.UnknownDerivedTypeHandling != JsonUnknownDerivedTypeHandling.FailSerialization)
        {
            throw new TypeScriptGenerationException(
                $"Polymorphic type '{stableName}' uses unsupported fallback behavior " +
                $"'{polymorphic.UnknownDerivedTypeHandling}'. A discriminated TypeScript union requires FailSerialization.");
        }

        if (polymorphic?.IgnoreUnrecognizedTypeDiscriminators == true)
        {
            throw new TypeScriptGenerationException(
                $"Polymorphic type '{stableName}' cannot ignore unrecognized discriminators because they are not representable " +
                "in a closed TypeScript union.");
        }

        var discriminatorPropertyName = polymorphic?.TypeDiscriminatorPropertyName ?? "$type";
        if (string.IsNullOrWhiteSpace(discriminatorPropertyName))
        {
            throw new TypeScriptGenerationException(
                $"Polymorphic type '{stableName}' must declare a non-empty JSON discriminator property name.");
        }

        var derivedTypes = new List<PolymorphicDerivedType>(derivedAttributes.Length);
        var registeredTypes = new HashSet<Type>();
        var registeredDiscriminators = new HashSet<string>(StringComparer.Ordinal);
        foreach (var attribute in derivedAttributes)
        {
            var derivedType = attribute.DerivedType;
            if (derivedType == type || !type.IsAssignableFrom(derivedType))
            {
                throw new TypeScriptGenerationException(
                    $"Derived type '{GetStableTypeName(derivedType)}' is not a proper subtype of polymorphic type '{stableName}'.");
            }

            if (derivedType.IsAbstract || derivedType.IsInterface || derivedType.ContainsGenericParameters)
            {
                throw new TypeScriptGenerationException(
                    $"Derived type '{GetStableTypeName(derivedType)}' for polymorphic type '{stableName}' must be a closed, concrete type.");
            }

            if (!registeredTypes.Add(derivedType))
            {
                throw new TypeScriptGenerationException(
                    $"Derived type '{GetStableTypeName(derivedType)}' is registered more than once for polymorphic type '{stableName}'.");
            }

            var discriminator = attribute.TypeDiscriminator;
            if (discriminator is not string and not int)
            {
                throw new TypeScriptGenerationException(
                    $"Derived type '{GetStableTypeName(derivedType)}' for polymorphic type '{stableName}' must declare a string or integer discriminator.");
            }

            if (discriminator is string stringDiscriminator && string.IsNullOrWhiteSpace(stringDiscriminator))
            {
                throw new TypeScriptGenerationException(
                    $"Derived type '{GetStableTypeName(derivedType)}' for polymorphic type '{stableName}' must declare a non-empty discriminator.");
            }

            var discriminatorKey = discriminator is string stringValue
                ? $"string:{stringValue}"
                : $"integer:{((int)discriminator).ToString(CultureInfo.InvariantCulture)}";
            if (!registeredDiscriminators.Add(discriminatorKey))
            {
                throw new TypeScriptGenerationException(
                    $"Discriminator {SerializeDiscriminator(discriminator)} is registered more than once for polymorphic type '{stableName}'.");
            }

            var collidingProperty = GetProperties(derivedType).FirstOrDefault(property =>
                string.Equals(GetSerializedPropertyName(property), discriminatorPropertyName, StringComparison.Ordinal));
            if (collidingProperty is not null)
            {
                throw new TypeScriptGenerationException(
                    $"Discriminator property '{discriminatorPropertyName}' for polymorphic type '{stableName}' collides with " +
                    $"serialized property '{GetStableTypeName(derivedType)}.{collidingProperty.Name}'.");
            }

            derivedTypes.Add(new PolymorphicDerivedType(derivedType, discriminator));
        }

        derivedTypes.Sort(static (left, right) =>
        {
            var discriminatorOrder = string.CompareOrdinal(
                GetDiscriminatorSortKey(left.Discriminator), GetDiscriminatorSortKey(right.Discriminator));
            return discriminatorOrder != 0
                ? discriminatorOrder
                : string.CompareOrdinal(GetStableTypeName(left.Type), GetStableTypeName(right.Type));
        });

        return new PolymorphicContract(discriminatorPropertyName, derivedTypes);
    }

    private static bool HasPolymorphicAttributes(Type type) =>
        type.IsDefined(typeof(JsonPolymorphicAttribute), inherit: false) ||
        type.IsDefined(typeof(JsonDerivedTypeAttribute), inherit: false);

    private static string GetSerializedPropertyName(PropertyInfo property) =>
        property.GetCustomAttribute<JsonPropertyNameAttribute>()?.Name ?? ToCamelCase(property.Name);

    private static string SerializeDiscriminator(object discriminator) =>
        discriminator is string value
            ? JsonSerializer.Serialize(value)
            : ((int)discriminator).ToString(CultureInfo.InvariantCulture);

    private static string GetDiscriminatorSortKey(object discriminator) =>
        discriminator is string value
            ? $"0:string:{value}"
            : $"1:integer:{((int)discriminator).ToString("D11", CultureInfo.InvariantCulture)}";

    private static string GetStableTypeName(Type type) => type.FullName ?? type.Name;

    private static TypeScriptGenerationException Unsupported(Type type, IReadOnlyList<string> path) => new(
        $"Unsupported type '{GetStableTypeName(type)}' at {string.Join(" -> ", path)}.");

    private static string ToCamelCase(string value)
    {
        if (string.IsNullOrEmpty(value) || char.IsLower(value[0]))
        {
            return value;
        }

        var uppercaseLength = 1;
        while (uppercaseLength < value.Length && char.IsUpper(value[uppercaseLength]))
        {
            uppercaseLength++;
        }

        if (uppercaseLength > 1 && uppercaseLength < value.Length)
        {
            uppercaseLength--;
        }

        return value[..uppercaseLength].ToLowerInvariant() + value[uppercaseLength..];
    }

    private sealed record PolymorphicContract(
        string DiscriminatorPropertyName,
        IReadOnlyList<PolymorphicDerivedType> DerivedTypes);

    private sealed record PolymorphicDerivedType(Type Type, object Discriminator);
}
