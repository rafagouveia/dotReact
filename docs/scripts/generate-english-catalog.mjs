import { existsSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { Children, isValidElement } from "react";
import { createServer } from "vite";

const docsRoot = resolve(import.meta.dirname, "..");
const catalogPath = resolve(docsRoot, "src/content.en.catalog.ts");
const checkOnly = process.argv.includes("--check");
const vite = await createServer({ root: docsRoot, server: { middlewareMode: true }, appType: "custom" });

try {
  const { docs } = await vite.ssrLoadModule("/src/content.tsx");
  const { CodeBlock, PairedCode, ReferenceTable } = await vite.ssrLoadModule("/src/components.tsx");
  const strings = new Set();
  for (const page of docs) collect(page.body);

  const expected = [...strings].sort((left, right) => left.localeCompare(right, "pt"));
  const current = existsSync(catalogPath)
    ? (await vite.ssrLoadModule("/src/content.en.catalog.ts")).englishText
    : {};
  const missing = expected.filter(value => typeof current[value] !== "string" || current[value].trim().length === 0);
  const stale = Object.keys(current).filter(value => !strings.has(value));
  const terminologyErrors = expected.filter(value => hasTerminologyError(value, current[value]));
  const structuralErrors = checkOnly
    ? compareStructures(docs, (await vite.ssrLoadModule("/src/content.en.tsx")).docsEn)
    : [];

  if (checkOnly) {
    if (missing.length || stale.length || terminologyErrors.length || structuralErrors.length) {
      if (missing.length) console.error(`Missing English translations (${missing.length}):\n${missing.slice(0, 20).join("\n")}`);
      if (stale.length) console.error(`Stale English translations (${stale.length}):\n${stale.slice(0, 20).join("\n")}`);
      if (terminologyErrors.length) console.error(`Invalid technical terminology (${terminologyErrors.length}):\n${terminologyErrors.slice(0, 20).join("\n")}`);
      if (structuralErrors.length) console.error(`PT/EN structural differences (${structuralErrors.length}):\n${structuralErrors.slice(0, 20).join("\n")}`);
      process.exitCode = 1;
    } else {
      console.log(`English catalog passed: ${expected.length} rich-content strings and ${docs.length} page trees have PT/EN parity.`);
    }
  } else {
    await generate(expected, missing, stale, current);
  }

  function collect(node) {
    if (typeof node === "string") {
      add(node);
      return;
    }
    if (!isValidElement(node)) {
      if (Array.isArray(node)) node.forEach(collect);
      return;
    }

    const props = node.props ?? {};
    if (node.type === CodeBlock) {
      add(props.label);
      return;
    }
    if (node.type === PairedCode) {
      add(props.csharpLabel);
      add(props.reactLabel);
      return;
    }
    if (node.type === ReferenceTable) {
      add(props.valueHeading);
      for (const row of props.rows ?? []) {
        add(row.name);
        add(row.defaultValue);
        add(row.description);
      }
      return;
    }

    if (typeof props.title === "string") add(props.title);
    if (typeof props["aria-label"] === "string") add(props["aria-label"]);
    Children.forEach(props.children, collect);
  }

  function add(value) {
    if (typeof value !== "string") return;
    const normalized = value.trim();
    if (normalized) strings.add(normalized);
  }
} finally {
  await vite.close();
}

async function generate(expected, missing, stale, current) {
  const translations = { ...current };
  let completed = 0;
  await mapWithConcurrency(missing, 5, async value => {
    translations[value] = shouldKeep(value) ? value : await translate(value);
    completed += 1;
    if (completed % 25 === 0 || completed === missing.length)
      console.log(`Translated ${completed}/${missing.length}`);
  });
  for (const value of stale) delete translations[value];
  for (const value of expected)
    translations[value] = normalizeTechnicalTranslation(value, translations[value]);

  const ordered = Object.fromEntries(expected.map(value => [value, translations[value]]));
  const output = `// Generated by scripts/generate-english-catalog.mjs. Review wording; do not edit the keys.\nexport const englishText: Readonly<Record<string, string>> = ${JSON.stringify(ordered, null, 2)};\n`;
  writeFileSync(catalogPath, output, "utf8");
  console.log(`Wrote ${expected.length} translations to ${catalogPath}`);
}

function normalizeTechnicalTranslation(source, translation) {
  let result = translation;
  if (/\bbanco|bancos\b/iu.test(source))
    result = result.replace(/\bbank(?:ing)?\b/giu, "database").replace(/\bbanks\b/giu, "databases");
  if (/\bhidrat/iu.test(source))
    result = result.replace(/\bmoistur(?:ize|izes|ized|izing)\b/giu, match => ({ moisturize: "hydrate", moisturizes: "hydrates", moisturized: "hydrated", moisturizing: "hydrating" })[match.toLowerCase()] ?? match);
  if (/\bporta\b/iu.test(source)) result = result.replace(/\bdoor\b/giu, "port");
  if (/\bidempotência\b/iu.test(source)) result = result.replace(/\bidempotence\b/giu, "idempotency");
  if (/busca props atuais/iu.test(source)) result = result.replace(/seeks current props/giu, "fetches current props");
  if (/^Estado e eventos hidratam/iu.test(source)) result = result.replace(/^Status and events/iu, "State and events");
  return result;
}

function hasTerminologyError(source, translation) {
  if (typeof translation !== "string") return false;
  if (/\bbanco|bancos\b/iu.test(source) && /\bbank(?:ing|s)?\b/iu.test(translation)) return true;
  if (/\bhidrat/iu.test(source) && /\bmoistur/iu.test(translation)) return true;
  if (/\bporta\b/iu.test(source) && /\bdoor\b/iu.test(translation)) return true;
  if (/\bidempotência\b/iu.test(source) && /\bidempotence\b/iu.test(translation)) return true;
  return false;
}

function compareStructures(portuguesePages, englishPages) {
  const englishById = new Map(englishPages.map(page => [page.id, page]));
  return portuguesePages.flatMap(page => {
    const english = englishById.get(page.id);
    if (!english) return [`${page.id}: missing English page`];
    return JSON.stringify(structureOf(page.body)) === JSON.stringify(structureOf(english.body))
      ? []
      : [`${page.id}: element tree differs`];
  });
}

function structureOf(node) {
  if (typeof node === "string") return "text";
  if (typeof node === "number") return "number";
  if (Array.isArray(node)) return node.map(structureOf);
  if (!isValidElement(node)) return node == null ? "empty" : typeof node;
  const type = typeof node.type === "string"
    ? node.type
    : typeof node.type === "symbol"
      ? node.type.description ?? "symbol"
      : node.type.displayName ?? node.type.name ?? "component";
  const details = type === "ReferenceTable" ? { rows: node.props.rows?.length ?? 0 } : undefined;
  return { type, details, children: Children.toArray(node.props.children).map(structureOf) };
}

function shouldKeep(value) {
  if (/^\d+(?:\.\d+)?$/u.test(value)) return true;
  if (/^[A-Z0-9_.+/@:[\]()-]{2,}$/u.test(value)) return true;
  if (/^(?:C#|React|TypeScript|PowerShell|Terminal|Program\.cs|page\.drx|package\.json)$/u.test(value)) return true;
  if (/^(?:app|src|Server|Domain|Application|Infrastructure|Presentation|public|vendor)\//u.test(value)) return true;
  return false;
}

async function translate(value) {
  const endpoint = new URL("https://translate.googleapis.com/translate_a/single");
  endpoint.searchParams.set("client", "gtx");
  endpoint.searchParams.set("sl", "pt");
  endpoint.searchParams.set("tl", "en");
  endpoint.searchParams.set("dt", "t");
  endpoint.searchParams.set("q", value);

  for (let attempt = 1; attempt <= 4; attempt += 1) {
    const response = await fetch(endpoint, { signal: AbortSignal.timeout(20_000) });
    if (response.ok) {
      const payload = await response.json();
      const translated = payload[0].map(segment => segment[0]).join("").trim();
      if (translated) return translated;
    }
    if (attempt < 4) await new Promise(resolve => setTimeout(resolve, attempt * 500));
  }
  throw new Error(`Could not translate: ${value}`);
}

async function mapWithConcurrency(values, concurrency, work) {
  let cursor = 0;
  async function worker() {
    while (cursor < values.length) {
      const index = cursor;
      cursor += 1;
      await work(values[index]);
    }
  }
  await Promise.all(Array.from({ length: Math.min(concurrency, values.length) }, worker));
}
